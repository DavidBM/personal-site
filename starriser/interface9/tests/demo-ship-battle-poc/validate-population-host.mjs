import assert from 'node:assert/strict';
import {createDirector} from './director.mjs';
import {preparePopulationAdmission} from './population-admission.mjs';
import {createSlotLayout} from './slot-layout.mjs';
import {exportDirector,prepareDirectorSnapshot} from './director-snapshot.mjs';
const d=createDirector(64),layout=createSlotLayout(d,64),request={fleet:0,type:0,cohort:1,visual:50,logical:1000,position:[-70,40,20]};
d.apply({revision:1,fleet:0,type:0,remaining:0});
const candidate=preparePopulationAdmission(d,request);assert.equal(d.population.count,64);assert.equal(candidate.director.population.count,114);
assert.equal(candidate.director.roster.count(0,0),50);assert.equal(candidate.director.roster.logicalCount(0,0),1000);
assert(!candidate.director.roster.isLive(0,0,0));
layout.request(Array.from({length:64},(_,i)=>64-i));layout.commit(layout.prepare(1));const physical=layout.physical.slice();
const extension=layout.prepareExtension(candidate.director.population);d.adopt(candidate.director,false);extension();
assert(physical.every((slot,id)=>layout.physical[id]===slot));assert(layout.status.pending);
while(layout.status.pending){const batch=layout.prepare();if(batch)layout.commit(batch);}
assert.equal(layout.logical[64],64);assert.equal(d.roster.sizeFor(1,0),1);assert.equal(d.roster.cohortOf(0,0,50),1);
d.apply({revision:d.revision+1,fleet:0,type:0,remaining:800});assert.equal(d.roster.count(0,0),40);
const next=preparePopulationAdmission(d,{...request,cohort:0,visual:30,logical:900});d.adopt(next.director,false);
assert.equal(d.roster.count(0,0),70);assert.equal(d.roster.logicalCount(0,0),1700);
d.apply({revision:d.revision+1,fleet:0,type:0,remaining:850});assert.equal(d.roster.count(0,0),35);assert.equal(d.roster.logicalCount(0,0),850);
assert.deepEqual(d.roster.batches[0].map(b=>b.logical),[0,400,450]);
const state=exportDirector(d);assert.deepEqual(exportDirector(prepareDirectorSnapshot(d,state)),state);
const old=d.population.keys.slice();assert.throws(()=>preparePopulationAdmission(d,[request,{...request,type:31,visual:256}]));assert.deepEqual(d.population.keys,old);
assert.throws(()=>preparePopulationAdmission(d,{...request,logical:2}));
assert.throws(()=>preparePopulationAdmission(d,{...request,visual:300}));
assert.throws(()=>preparePopulationAdmission(d,{...request,position:[NaN,0,0]}));
assert.throws(()=>preparePopulationAdmission(d,{...request,velocity:[100,0,0]}));
assert.throws(()=>preparePopulationAdmission(d,{...request,at:100}),/current simulation boundary/);
const bad=structuredClone(state);bad.groups[0].batches[1].logical++;assert.throws(()=>prepareDirectorSnapshot(d,bad),/logical casualties/);
const partial=createDirector(1000,{reserveFraction:.2}),prepared=preparePopulationAdmission(partial,request);partial.adopt(prepared.director,false);
const reserved=partial.roster.batches[0][1];assert.equal(partial.roster.isLive(0,0,reserved.first),false);
assert.deepEqual(exportDirector(prepareDirectorSnapshot(partial,exportDirector(partial))),exportDirector(partial));
partial.apply({revision:partial.revision+1,fleet:0,admit:1});assert(partial.roster.isLive(0,0,reserved.first));
console.log('ok: asymmetric admission, mixed cohort tags, batch-weighted losses, stable IDs and packing, atomic rejection, snapshots and partial reserves');

const fractions=createDirector(1000,{reserveFraction:.2});fractions.adopt(preparePopulationAdmission(fractions,request).director,false);
fractions.apply({revision:fractions.revision+1,fleet:0,cohort:1,survivalFraction:.8});
const admittedBefore=fractions.roster.cohorts[0][1].quota;
fractions.apply({revision:fractions.revision+1,fleet:0,admit:1});
assert(fractions.roster.cohorts[0][1].quota>admittedBefore);
assert.deepEqual(exportDirector(prepareDirectorSnapshot(fractions,exportDirector(fractions))),exportDirector(fractions));
console.log('ok: partial cohort losses and later reserve admission preserve exact cohort accounting');
