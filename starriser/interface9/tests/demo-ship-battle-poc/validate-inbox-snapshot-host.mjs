import assert from 'node:assert/strict';
import {createEventInbox,EVENT_LIMITS} from './event-inbox.mjs';
const packet=(sequence,effectiveAt,extra={})=>({id:`p${sequence}`,sequence,effectiveAt,commands:[],...extra});
const state=(through,pending=[],lanes=Array(EVENT_LIMITS.lanes).fill(0))=>({through,pending,lanes});
const original=createEventInbox();original.receive(packet(1,1),0);original.drain(1,()=>{});
original.receive(packet(3,3),1);original.receive(packet(4,8,{lane:2,revision:2}),1);
const source=state(2,[packet(2,7,{lane:2,revision:1})]);source.lanes[2]=1;
const before=original.status,restored=original.restore(source,2);
assert.deepEqual(original.status,before);assert.equal(original.history.length,1);
assert.equal(restored.status.receiptPrefix,4);assert.equal(restored.status.pending,2);
const seen=[];restored.drain(3,e=>seen.push(e.sequence));restored.drain(9,e=>seen.push(e.sequence));assert.deepEqual(seen,[3,4]);
assert.equal(original.status.pending,2);assert.throws(()=>restored.restore(state(3),10),/regressed/);
assert.equal(restored.receive(packet(2,7,{lane:2,revision:1}),10).status,'duplicate');
const future=createEventInbox();future.receive(packet(1,10),0);future.receive(packet(2,20),0);
const futureRestored=future.restore(state(1,[packet(1,10)]),5);assert.equal(futureRestored.status.receiptPrefix,2);assert.equal(futureRestored.status.pending,2);
futureRestored.drain(25,e=>seen.push(e.sequence));assert.deepEqual(seen,[3,4,1,2]);
const hole=createEventInbox();hole.receive(packet(9,20),0);const repaired=hole.restore(state(8),10);
assert.equal(repaired.status.receiptPrefix,9);assert.equal(repaired.status.receiptGaps,0);assert.equal(repaired.status.pending,1);
const bads=[state(-1),state(0,[packet(1,20)]),state(5,[packet(1,2)]),state(5,[packet(1,20),packet(1,20)]),state(5,[],[])];
for(const bad of bads)assert.throws(()=>original.restore(bad,2));assert.deepEqual(original.status,before);
const late=createEventInbox();late.receive(packet(3,1),3);const base=late.restore(state(2),2);base.drain(2,()=>assert.fail());base.drain(3,()=>{});assert.equal(base.history.at(-1).receivedAt,3);
console.log('Snapshot watermarks repair gaps, preserve newer/future packets, reconcile lanes and reject stale or malformed restores without mutation.');
const laneState=state(2,[packet(1,20,{lane:2,revision:1}),packet(2,30,{lane:2,revision:1})]);laneState.lanes[2]=1;
assert.throws(()=>createEventInbox().restore(laneState,10),/Duplicate/);
const lanePast=createEventInbox();lanePast.receive(packet(1,1,{lane:7,revision:8}),0);lanePast.drain(1,()=>{});
assert.throws(()=>lanePast.restore(state(1),2),/lane revision regressed/);
const rejectedFact=createEventInbox();rejectedFact.receive(packet(10,1),0);rejectedFact.drain(1,()=>{throw Error('partial report');});
assert.throws(()=>rejectedFact.restore(state(9),2),/watermark regressed/);
const full=createEventInbox();for(let i=1;i<=1024;i++)full.receive(packet(i,30),0);
assert.throws(()=>full.restore(state(0,[packet(0,30)]),10));assert.equal(full.status.pending,1024);
const combined=createEventInbox();combined.receive(packet(1025,30),0);
const packed=Array.from({length:1024},(_,i)=>packet(i+1,20));assert.throws(()=>combined.restore(state(1024,packed),10),/full/);
const big=createEventInbox(),many=Array.from({length:16},(_,i)=>packet(i+1,20,{commands:Array(50).fill('x'.repeat(4999))}));
for(let i=17;i<=20;i++)big.receive(packet(i,30,{commands:Array(50).fill('x'.repeat(4999))}),0);
assert.throws(()=>big.restore(state(16,many),10),/full/);assert.equal(big.status.pending,4);
console.log('Recovery also rejects duplicate lanes, regressed lane watermarks, partial-report cuts and combined queue/byte overflow.');
