import assert from 'node:assert/strict';
import {createEventQueue} from './event-queue.mjs';
const event=(id,effectiveAt,deliveredAt=effectiveAt)=>({id,effectiveAt,deliveredAt,commands:[{fleet:0,joined:true}]});
const input=[event('future',4,1),event('late',2,5),event('now',1)],queue=createEventQueue(input),seen=[];
const almost=createEventQueue([event('boundary',1)]);
assert.equal(almost.drain(1-1e-8,()=>assert.fail('event was activated before its exact window')),0);
assert.equal(almost.drain(1,()=>{}),1);
input[0].effectiveAt=0;input[0].commands[0].joined=false;
const apply=(value,admission)=>{seen.push(admission);assert(Object.isFrozen(value.commands));assert(value.commands[0].joined);};
assert.equal(queue.nextBoundary(0,10),1);assert.equal(queue.drain(1,apply),1);
assert.equal(queue.nextBoundary(1,10),4);queue.drain(3,apply);assert.equal(seen.length,1);
queue.drain(4,apply);assert.equal(seen[1].id,'future');assert.equal(seen[1].late,false);
queue.drain(9,apply);assert.equal(seen[2].id,'late');assert.equal(seen[2].appliedAt,9);assert(seen[2].late);
assert(queue.complete);assert.throws(()=>queue.drain(8,apply));assert.throws(()=>queue.nextBoundary(9,8));
queue.drain(9,()=>assert.fail('duplicate admission'));
const duplicate=createEventQueue([event('same',1),event('same',1)]);assert.equal(duplicate.drain(2,()=>{}),1);
assert.throws(()=>createEventQueue([event('same',1),event('same',2)]));
assert.throws(()=>createEventQueue([event('bad',NaN)]));assert.throws(()=>createEventQueue(Array(4097).fill(event('overflow',1))));
const retry=createEventQueue([event('retry',0)]);assert.throws(()=>retry.drain(0,()=>{throw new Error('admission rejected');}));
assert(!retry.complete);assert.equal(retry.history.length,0);retry.drain(0,()=>{});assert(retry.complete);
console.log('Event journal snapshots inputs, separates delivery/effect, admits late events at the current clock, rejects rewinds/conflicts/overflow and records only successful callbacks.');
